<?php

namespace App\Services;

use Auth;
use Illuminate\Support\Facades\Storage;
use Intervention\Image\Facades\Image;

class UploadService {

    /**
     * Extensions that must never be written to a publicly served directory,
     * because the web server (or a misconfigured proxy) may execute or
     * interpret them. Kept as a hard deny list at the storage layer so that
     * a missing validation rule in any controller cannot lead to RCE.
     */
    public const BLOCKED_EXTENSIONS = [
        'php', 'php2', 'php3', 'php4', 'php5', 'php6', 'php7', 'php8', 'phps', 'phtm', 'phtml',
        'pht', 'phar', 'inc', 'module', 'shtml', 'shtm', 'stm',
        'cgi', 'pl', 'py', 'rb', 'sh', 'bash', 'zsh', 'ksh',
        'asp', 'aspx', 'ashx', 'asmx', 'ascx', 'axd', 'cer', 'asa', 'cshtml',
        'jsp', 'jspx', 'jsw', 'jsv', 'jspf', 'jhtml',
        'exe', 'com', 'bat', 'cmd', 'msi', 'scr', 'dll', 'so', 'jar', 'war', 'ear',
        'htaccess', 'htpasswd', 'user', 'ini', 'conf', 'config', 'env',
    ];

    /**
     * Build a safe, non executable file name for an uploaded file.
     * The name itself is always generated by us (never taken from the client)
     * and the extension is sanitized against a deny list.
     */
    public static function safeFileName($requestFile): string {
        $extension = strtolower((string) $requestFile->getClientOriginalExtension());

        // Strip anything that is not a plain alphanumeric extension
        // (null bytes, path separators, "php\x00.jpg" style tricks, ...)
        $extension = preg_replace('/[^a-z0-9]/', '', $extension) ?? '';

        // Fall back to the extension guessed from the real file contents
        if ($extension === '') {
            $extension = strtolower((string) $requestFile->guessExtension());
            $extension = preg_replace('/[^a-z0-9]/', '', $extension) ?? '';
        }

        // Never store an executable / interpretable extension in public storage
        if ($extension === '' || in_array($extension, self::BLOCKED_EXTENSIONS, true) || strlen($extension) > 10) {
            $extension = 'bin';
        }

        return uniqid('', true) . time() . '.' . $extension;
    }

    public static function upload($requestFile, $folder) {
        if (Auth::user() && Auth::user()->school_id) {
            $folder = Auth::user()->school_id.'/'.$folder;
        } else {
            $folder = 'super-admin/'.$folder;
        }
        $file_name = self::safeFileName($requestFile);
        $extension = strtolower(pathinfo($file_name, PATHINFO_EXTENSION));

        if (in_array($extension, ['jpg', 'jpeg', 'png'], true) && self::canProcessImage()) {
            // Check the Extension should be jpg or png and do compression
            // Re-encoding also strips any PHP payload embedded inside the image
            $image = Image::make($requestFile)->encode(null, 60);
            Storage::disk('public')->put($folder . '/' . $file_name, $image);
        } else {
            // On servers without the GD extension, or for SVG/other allowed file types,
            // store the uploaded bytes directly instead of crashing the request.
            $stream = fopen($requestFile->getRealPath(), 'rb');
            if ($stream !== false) {
                Storage::disk('public')->put($folder . '/' . $file_name, $stream);
                fclose($stream);
            } else {
                $requestFile->storeAs($folder, $file_name, 'public');
            }
        }
        return $folder . '/' . $file_name;
    }

    /**
     * @param $image = rawOriginalPath
     * @return bool
     */
    public static function delete($image) {
        if ($image && Storage::disk('public')->exists($image)) {
            return Storage::disk('public')->delete($image);
        }


        //Image does not exist in server so feel free to upload new image
        return true;
    }

    private static function canProcessImage(): bool
    {
        return extension_loaded('gd')
            && function_exists('imagecreatefromstring')
            && class_exists(\Intervention\Image\ImageManager::class);
    }

}
